CREATE DATABASE IF NOT EXISTS derma_check
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE derma_check;

-- Desativa checagem de chaves para permitir recriação limpa
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS diario_pele;
DROP TABLE IF EXISTS fotos_lesao;
DROP TABLE IF EXISTS lesoes;
DROP TABLE IF EXISTS usuarios;

SET FOREIGN_KEY_CHECKS = 1;

-- 1. Tabela de Usuários (Clientes e Profissionais)
CREATE TABLE usuarios (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome VARCHAR(150) NOT NULL,
  email VARCHAR(254) NOT NULL,
  senha VARCHAR(255) NOT NULL,
  tipo_usuario ENUM('CLIENTE', 'PROFISSIONAL') NOT NULL,
  crm VARCHAR(30) NULL,
  especialidade VARCHAR(120) NULL,
  telefone VARCHAR(20) NULL,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY usuarios_email_unique (email)
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

-- 2. Tabela de Lesões Cutâneas (RN01, RN03, RN06)
CREATE TABLE lesoes (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  usuario_id INT UNSIGNED NOT NULL,
  nome_identificacao VARCHAR(100) NOT NULL,
  localizacao_corpo VARCHAR(100) NOT NULL,
  data_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  observacoes TEXT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_lesoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

-- 3. Tabela de Fotografias das Lesões (RN02, RN07)
CREATE TABLE fotos_lesao (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  lesao_id INT UNSIGNED NOT NULL,
  url_foto VARCHAR(255) NOT NULL,
  data_foto DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  observacao_foto TEXT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_fotos_lesao FOREIGN KEY (lesao_id) REFERENCES lesoes(id) ON DELETE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

-- 4. Tabela de Registros do Diário da Pele (RN01 a RN05)
CREATE TABLE diario_pele (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  usuario_id INT UNSIGNED NOT NULL,
  data_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  mudancas_percebidas TEXT NULL,
  sintomas TEXT NULL,
  exposicao_solar ENUM('BAIXO', 'MODERADO', 'ALTO') NOT NULL DEFAULT 'BAIXO',
  url_foto VARCHAR(255) NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_diario_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

-- 5. Tabela de Lembretes (CA01 a CA07, RN08)
CREATE TABLE IF NOT EXISTS lembretes (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  usuario_id INT UNSIGNED NOT NULL,
  titulo VARCHAR(150) NOT NULL,
  tipo ENUM('FOTO', 'DIARIO', 'CONSULTA', 'OUTRO') NOT NULL DEFAULT 'OUTRO',
  data_lembrete DATETIME NOT NULL,
  observacoes TEXT NULL,
  concluido TINYINT(1) NOT NULL DEFAULT 0,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_lembretes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;